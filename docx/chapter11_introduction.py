        'в NVS и обработку запросов на подпись через серийный протокол.',

        '2. Разработать программный мост (bridge) на языке Python, '
        'транслирующий стандартный протокол SSH-агента в серийный протокол '
        'ESP32 с поддержкой операций блокировки и разблокировки.',

        '3. Разработать клиентское приложение на языке Go, обеспечивающее '
