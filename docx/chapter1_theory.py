        'SubBytes (побайтовая подстановка с использованием S-блока), ShiftRows (циклический '
        'сдвиг строк матрицы состояния), MixColumns (умножение столбцов на фиксированный '
        'полином в GF(2⁸)) и AddRoundKey (побитовое XOR с раундовым ключом). '
