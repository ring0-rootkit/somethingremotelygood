        'количество итераций c = 100000, длина соли S = 16 байт (128 бит, генерируется '
        'аппаратным ГСЧ ESP32), длина выходного ключа dkLen = 32 байта (256 бит). Выбор '
        '100000 итераций обеспечивает баланс между безопасностью и временем выполнения на '
        'микроконтроллере ESP32: при тактовой частоте 160 МГц процесс деривации занимает '
        'приблизительно 3-5 секунд, что является приемлемым для пользователя, но делает '
        'атаку перебором крайне затратной.',
