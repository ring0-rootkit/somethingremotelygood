        'следующие параметры: пароль (P), случайная соль (S), количество итераций (c), '
        'длина выходного ключа (dkLen) и псевдослучайная функция (PRF), обычно HMAC. '
        'Выходной ключ вычисляется как: DK = T1 || T2 || ... || Tdklen/hlen, где '
