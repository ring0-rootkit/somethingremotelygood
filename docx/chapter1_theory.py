        'использование предвычисленных таблиц (rainbow tables), поскольку каждая соль '
        'требует отдельной таблицы; (2) гарантирует, что одинаковые пароли порождают '
        'различные ключи при разных значениях соли. В системе соль генерируется '
        'функцией esp_random() и сохраняется в NVS ESP32 под ключом «salt» в открытом '
        'виде, так как знание соли не снижает безопасности системы [8].',
