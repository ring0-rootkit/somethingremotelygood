        'через стандартную сетевую инфраструктуру. Недостатки: необходимость '
        'настройки WiFi-подключения на ESP32, расширение поверхности атаки '
        '(устройство доступно из сети), необходимость TLS для защиты канала. '
        'Для безопасности рекомендуется использовать mTLS с сертификатами, '
        'что значительно усложняет первоначальную настройку.',
